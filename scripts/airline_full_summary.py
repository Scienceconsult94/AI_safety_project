"""Whole-domain airline summary: the sample (20 tasks), the rest (30) and all 50 side by side, with the pre-registered
predictions P1-P10 of airline_full/PLAN.md.

Inputs:
  airline_full/audit_log.csv                      scripts/build_audit_log.py --ids population
  results/static_scan.csv, sample.json
  results/runs/{sample20,rest30}_{pass3,gt}_haiku.results.json     stock agent runs (substring scorer)
  results/probe_2j.csv                            check 2j (P5, P6)
  airline_full/handcheck_fresh_r2/key.csv, labels_c.csv, labels_d.csv     judge hand-check, round 2 (P8)
  results/v2/rescore_rest30.csv                   re-score of the stock rest runs under the block-2 configurations (P9)
  results/v2/runs/v2_rest30_pass3_haiku/results.json                      fresh v2 run on the rest (P10)
  results/v2/runs/v2_cf32_A_gt_haiku/results.json, v2_cf32_B_gt_haiku/results.json   task-32 arms (P7)
  results/rereview_rest.csv                       blind re-review of rest tasks 33, 35, 39
Output: airline_full/summary_numbers.md. A missing input leaves the rows that depend on it marked "pending".
The sample column must reproduce the block-1 numbers (root summary_numbers.md); the script asserts the block-1 count
that includes the no-op class (18/20). Headline counts leave the no-op class (2a, 2b) out and report it separately.
Usage (from ==Project):  python -I scripts/airline_full_summary.py
"""

from __future__ import annotations

import csv
import json
import sys
from pathlib import Path

import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parent))
import make_summary as ms  # noqa: E402  (block-1 helpers: defective_task_ids, fmt_share, agent_run_stats, ...)

ROOT = ms.ROOT
FULL = ROOT / "airline_full"
RES = ROOT / "results"
V2 = RES / "v2"
# the sample's Wilson 95% intervals as written in the predictions (airline_full/PLAN.md, section 3)
PLAN_CI = {"P1": (0.70, 0.97), "P2": (0.58, 0.92), "P3": (0.43, 0.82)}
CONFIGS = ("v1", "S_hash", "S_comm", "S_nl", "S_all_t1", "T2_stock", "V2")


def read_csv(p: Path) -> list[dict]:
    if not p.exists():
        return []
    with open(p, encoding="utf-8", newline="") as fp:
        return list(csv.DictReader(fp))


def sims(*paths: Path) -> list[dict]:
    out = []
    for p in paths:
        if p.exists():
            out += json.loads(p.read_text(encoding="utf-8"))["simulations"]
    return out


def ok(s: dict) -> bool:
    r = (s.get("reward_info") or {}).get("reward")
    return r is not None and float(r) == 1.0


def pass3(simlist: list[dict], ids) -> tuple[int, int]:
    """Tasks whose first three trials all have reward 1.0 (pass^3), over tasks with >= 3 trials."""
    per: dict[str, list] = {}
    for s in simlist:
        if str(s["task_id"]) in ids and s.get("termination_reason") != "infrastructure_error":
            per.setdefault(str(s["task_id"]), []).append((int(s["trial"]), ok(s)))
    el = [sorted(v) for v in per.values() if len(v) >= 3]
    return sum(all(x for _, x in v[:3]) for v in el), len(el)


def mean_pass1(simlist: list[dict], ids) -> tuple[int, int]:
    """Successful trials / evaluated trials (tau2's pass^1 when every task has the same number of trials)."""
    v = [ok(s) for s in simlist if str(s["task_id"]) in ids and s.get("termination_reason") != "infrastructure_error"]
    return sum(v), len(v)


def fmt(k: int, n: int) -> str:
    return ms.fmt_share(k, n) if n else "n/a"


def main() -> int:
    sample = json.loads((ROOT / "sample.json").read_text(encoding="utf-8"))
    S = [str(t) for t in sample["task_ids"]]
    A = [str(t) for t in sample["population_ids"]]
    R = [t for t in A if t not in S]
    sets = (("sample", S), ("rest", R), ("all", A))
    audit = pd.read_csv(FULL / "audit_log.csv", dtype=str, keep_default_na=False)
    scan = pd.read_csv(RES / "static_scan.csv", dtype={"task_id": str})
    noop = set(scan.loc[scan["noop_pass"] == 1, "task_id"])
    assert len(ms.defective_task_ids(audit, S)) == 18, "sample count with the no-op class differs from block 1 (18/20)"

    L = ["# Airline, whole domain: the sample, the rest and all 50 tasks", "",
         "Generated by `scripts/airline_full_summary.py` from `airline_full/audit_log.csv` "
         "(`scripts/build_audit_log.py --ids population`) and the run files; pre-registration: `airline_full/PLAN.md`. "
         "The sample column reproduces the published block-1 numbers (root `summary_numbers.md`). "
         "A task counts as defective when at least one row has defect = 1 and severity high or medium; the headline rows "
         "leave out the documented no-op class (2a, 2b), which is reported separately (last row of Table 1); "
         "shares are k/n = share [Wilson 95% interval].", ""]

    # ---- Table 1: defective tasks
    rows1 = [
        ("defective tasks, all checks (headline; the no-op class 2a, 2b is reported separately)", lambda ids: len(ms.defective_task_ids(audit, ids, exclude_checks=ms.NOOP_CHECKS))),
        ("static and probe checks only (no agent runs)", lambda ids: len(ms.defective_task_ids(audit, ids, exclude_checks=ms.NOOP_CHECKS, exclude_methods=(ms.AGENT_RUN,)))),
        ("also excluding check 2g (applies only to the substring scorer the runs selected)", lambda ids: len(ms.defective_task_ids(audit, ids, exclude_checks=ms.NOOP_CHECKS + ms.SUBSTRING_CHECKS))),
        ("excluding every no-op-derived defect (2a, 2b, and 2k on a no-op task)", lambda ids: ms.defective_tasks_noop_free(audit, ids, noop)),
        ("agent-run checks only (1e, 4f, 5c, 5d, 5e, 5f)", lambda ids: len(ms.defective_task_ids(audit, ids, methods=(ms.AGENT_RUN,)))),
        ("tasks whose only confirmed defects come from agent runs", lambda ids: ms.agent_run_only_tasks(audit, ids)),
        ("counting the no-op class (2a, 2b), all checks", lambda ids: len(ms.defective_task_ids(audit, ids))),
        ("counting the no-op class, static and probe checks only", lambda ids: len(ms.defective_task_ids(audit, ids, exclude_methods=(ms.AGENT_RUN,)))),
        ("tasks that pass with an empty answer (no-op, reported separately)", lambda ids: len(noop & set(ids))),
    ]
    L += ["## Table 1. Defective tasks", "", "| quantity | sample (20) | rest (30) | all (50) |", "|---|---|---|---|"]
    for label, f in rows1:
        L.append(f"| {label} | " + " | ".join(fmt(f(ids), len(ids)) for _, ids in sets) + " |")
    a = ms.normalize(audit)
    unrev = {name: int(((a["defect"] == 1) & a["severity"].isin(ms.CONFIRMED) & (a["skeptic_ok"] == "") & a["task_id"].isin(ids)).sum())
             for name, ids in sets}
    rej = {name: int(((a["defect"] == 1) & a["severity"].isin(ms.CONFIRMED) & (a["skeptic_ok"] == "0") & a["task_id"].isin(ids)).sum())
           for name, ids in sets}
    L += ["", f"High or medium defect rows without an adversarial verdict: sample {unrev['sample']}, rest {unrev['rest']}, all {unrev['all']}. "
          f"Rows the adversarial review rejected but the log still carries as defects: sample {rej['sample']}, rest {rej['rest']}.", ""]

    # ---- Table 2: per category
    L += ["## Table 2. Defective tasks per category (the no-op class 2a, 2b is reported separately)", "", "| category | sample | rest | all |", "|---|---|---|---|"]
    pc = {name: ms.per_category(audit, ids, exclude_checks=ms.NOOP_CHECKS) for name, ids in sets}
    for c, title in ms.CATEGORIES.items():
        L.append(f"| {c}. {title} | " + " | ".join(f"{pc[name][c]}/{len(ids)}" for name, ids in sets) + " |")

    # ---- Table 3: rows per check
    L += ["", "## Table 3. Confirmed defect rows per check (rows / distinct tasks)", "",
          "| check | sample | rest | all |", "|---|---|---|---|"]
    per = {name: {c: (r, t) for c, r, t in ms.rows_per_check(audit, ids)} for name, ids in sets}
    for c in sorted(per["all"], key=ms._check_key):
        L.append(f"| {c} | " + " | ".join("{} / {}".format(*per[name].get(c, (0, 0))) for name, _ in sets) + " |")

    # ---- Table 4: agent runs
    runs = {"haiku": sims(RES / "runs" / "sample20_pass3_haiku.results.json", RES / "runs" / "rest30_pass3_haiku.results.json"),
            "gt": sims(RES / "runs" / "sample20_gt_haiku.results.json", RES / "runs" / "rest30_gt_haiku.results.json")}
    st = {name: ms.agent_run_stats(runs, ids) for name, ids in sets}
    L += ["", "## Table 4. Agent runs (claude-haiku-5-5 agent and user, substring scorer, three trials per task)", "",
          "| quantity | sample | rest | all |", "|---|---|---|---|"]
    L.append("| pass^3: tasks with all three trials at reward 1.0 | " + " | ".join(fmt(*st[n]["pass3"]) for n, _ in sets) + " |")
    L.append("| pass^1, mean over all trials (tau2's estimator) | " + " | ".join(fmt(*mean_pass1(runs["haiku"], ids)) for _, ids in sets) + " |")
    L.append("| pass^1, first trial only (block-1 summary estimator) | " + " | ".join(fmt(*st[n]["pass1"]) for n, _ in sets) + " |")
    L.append("| tasks solved in 1 or 2 of 3 trials (unstable) | " + " | ".join(fmt(st[n]["s12"], st[n]["n3"]) for n, _ in sets) + " |")
    L.append("| ground-truth agent reaches the target state | " + " | ".join(fmt(*st[n]["gt"]) for n, _ in sets) + " |")
    L.append("| infrastructure_error simulations excluded | " + " | ".join(str(st[n]["infra"]) for n, _ in sets) + " |")
    L += ["", f"Ground-truth agent fails on: sample {', '.join(st['sample']['gt_fail']) or 'none'}; rest {', '.join(st['rest']['gt_fail']) or 'none'}.", ""]

    # ---- Table 5: review stages on the rest
    rr = read_csv(RES / "rereview_rest.csv")
    key = {r["item"]: r for r in read_csv(FULL / "handcheck_fresh_r2" / "key.csv")}
    lab = {x: {r["item"]: r["label"] for r in read_csv(FULL / "handcheck_fresh_r2" / f"labels_{x}.csv")} for x in ("c", "d")}
    L += ["## Table 5. Review stages", "", "| stage | result |", "|---|---|"]
    if rr:
        for col, name in (("original_defect", "original reviewer labels"), ("corrected_defect", "labels after the adversarial review")):
            pairs = [(r[col], r["blind_defect"]) for r in rr if r[col] != ""]
            L.append(f"| blind re-review of rest tasks 33, 35, 39 vs {name} | {sum(x == y for x, y in pairs)}/{len(pairs)} rows agree |")
    hc = {}
    if key and all(lab.values()):
        for x in ("c", "d"):
            jm = lambda i: "met" if key[i]["judge_met"] == "True" else "unmet"  # noqa: E731
            tg = [i for i in key if key[i]["target"] == "1"]
            dc = [i for i in key if key[i]["target"] == "0"]
            hc[x] = (sum(lab[x].get(i) == jm(i) for i in tg), len(tg), sum(lab[x].get(i) == jm(i) for i in dc), len(dc))
            L.append(f"| judge hand-check round 2, reader {x.upper()} vs judge | targets {hc[x][0]}/{hc[x][1]}, decoys {hc[x][2]}/{hc[x][3]} |")
    L.append("")

    # ---- Table 6: block 2 on the rest (Q5)
    rs = read_csv(V2 / "rescore_rest30.csv")
    fresh = sims(V2 / "runs" / "v2_rest30_pass3_haiku" / "results.json")
    L += ["## Table 6. Block 2 on the rest tasks (Q5)", ""]
    p9 = None
    if rs:
        hk = [r for r in rs if r["agent"] == "haiku"]
        gt = [r for r in rs if r["agent"] != "haiku"]
        L += ["Re-score of the recorded stock rest runs (`results/v2/rescore_summary_rest30.md`):", "",
              f"| config | haiku sims passing ({len(hk)}) | haiku tasks 3/3 ({len({r['task_id'] for r in hk})}) | gt sims passing ({len(gt)}) |",
              "|---|---|---|---|"]
        for c in CONFIGS:
            if f"{c}_reward" not in rs[0]:
                continue
            good = [r for r in hk if r.get(f"{c}_reward") == "1.0"]
            per_t: dict[str, int] = {}
            for r in good:
                per_t[r["task_id"]] = per_t.get(r["task_id"], 0) + 1
            L.append(f"| {c} | {len(good)} | {sum(1 for v in per_t.values() if v == 3)} | {sum(1 for r in gt if r.get(f'{c}_reward') == '1.0')} |")
        p9 = sum(1 for r in rs if r["S_hash_reward"] != r["v1_reward"] or r["S_comm_reward"] != r["v1_reward"])
        L += ["", f"Simulations whose reward changes under a deterministic switch alone (canonical hash or word-boundary communicate check): {p9} of {len(rs)}.", ""]
    else:
        L += ["Re-score of the stock rest runs: pending.", ""]
    v1p3 = pass3(runs["haiku"], set(R))
    v2p3 = pass3(fresh, set(R)) if fresh else None
    L.append(f"Haiku pass^3 on the rest: stock protocol (v1) {fmt(*v1p3)}; fresh run under the full v2 protocol "
             f"{fmt(*v2p3) if v2p3 else 'pending'}.")
    L.append("")

    # ---- Table 7: task 32 (Q3)
    arms = {x: sims(V2 / "runs" / f"v2_cf32_{x}_gt_haiku" / "results.json") for x in ("A", "B")}
    L += ["## Table 7. Task 32, ground-truth agent under the full v2 protocol, 10 trials per arm (Q3)", ""]
    p7 = None
    if all(len(v) >= 10 for v in arms.values()):  # both arms complete (a run in progress leaves a partial file)
        k = {x: (sum(ok(s) for s in v), len(v)) for x, v in arms.items()}
        p7 = k["B"][0] - k["A"][0]
        L += ["| arm | text | passes |", "|---|---|---|",
              f"| A | v2.1 as published | {k['A'][0]}/{k['A'][1]} |",
              f"| B | without the sentence on the Visa card | {k['B'][0]}/{k['B'][1]} |", "",
              f"B - A = {p7} (pre-registered rule: the sentence is taken to cause the failures if B - A >= 3).", ""]
    else:
        L += ["pending", ""]

    # ---- Table 8: predictions
    j2 = read_csv(RES / "probe_2j.csv")
    rec = [r for r in j2 if r["run"] != "null"]
    differing = {(r["run"], r["task_id"], r["trial"]) for r in rec if r["differs"] == "1"}
    null_pass = {}
    for r in (r for r in j2 if r["run"] == "null"):
        null_pass[r["task_id"]] = null_pass.get(r["task_id"], True) and r["semantic_majority"] == "1"
    info_tasks_passing = sorted((t for t, v in null_pass.items() if v), key=int)
    sh = {}
    for pid, f in (("P1", lambda ids: len(ms.defective_task_ids(audit, ids))),
                   ("P2", lambda ids: len(ms.defective_task_ids(audit, ids, exclude_checks=ms.NOOP_CHECKS))),
                   ("P3", lambda ids: len(ms.defective_task_ids(audit, ids, exclude_methods=(ms.AGENT_RUN,))))):
        k = f(A)
        lo, hi = PLAN_CI[pid]
        sh[pid] = (k, len(A), lo <= k / len(A) <= hi)

    def verdict(x):
        return "pending" if x is None else ("holds" if x else "does not hold")

    preds = [
        ("P1", f"whole-domain defective share, all checks counting the no-op class as pre-registered, in [{PLAN_CI['P1'][0]}, {PLAN_CI['P1'][1]}]", f"{sh['P1'][0]}/50 = {sh['P1'][0] / 50:.2f}", sh["P1"][2]),
        ("P2", f"whole-domain share without 2a/2b in [{PLAN_CI['P2'][0]}, {PLAN_CI['P2'][1]}]", f"{sh['P2'][0]}/50 = {sh['P2'][0] / 50:.2f}", sh["P2"][2]),
        ("P3", f"whole-domain share from static and probe rows, counting the no-op class as pre-registered, in [{PLAN_CI['P3'][0]}, {PLAN_CI['P3'][1]}]", f"{sh['P3'][0]}/50 = {sh['P3'][0] / 50:.2f}", sh["P3"][2]),
        ("P4", "rest pass^3 above the sample's 0.60", f"{v1p3[0]}/{v1p3[1]} = {v1p3[0] / v1p3[1]:.3f}" if v1p3[1] else "n/a", (v1p3[0] / v1p3[1] > 0.60) if v1p3[1] else None),
        ("P5", "semantic scorer: the empty trajectory passes the same 23 tasks, no task with required information",
         f"tasks with required information passed by the empty trajectory: {', '.join(info_tasks_passing) or 'none'} (of {len(null_pass)})",
         (not info_tasks_passing and len(noop) == 23) if null_pass else None),
        ("P6", "recorded runs: semantic and substring verdicts differ on at most 2 trials",
         f"{len(differing)} differing trials of {len({(r['run'], r['task_id'], r['trial']) for r in rec})}", (len(differing) <= 2) if rec else None),
        ("P7", "task 32: arm B passes at least 3 more of 10 than arm A", "pending" if p7 is None else f"B - A = {p7}", None if p7 is None else p7 >= 3),
        ("P8", "each blind reader agrees with the judge on at least 18 of 20 items (round 2 targets)",
         "; ".join(f"{x.upper()} {v[0]}/{v[1]}" for x, v in hc.items()) or "pending", (all(v[0] >= 18 for v in hc.values())) if hc else None),
        ("P9", "rest runs: the deterministic v2 switches change no reward", "pending" if p9 is None else f"{p9} changed", None if p9 is None else p9 == 0),
        ("P10", "rest: Haiku pass^3 under v2 within 0.10 of v1",
         "pending" if not v2p3 else f"v1 {v1p3[0] / v1p3[1]:.3f}, v2 {v2p3[0] / v2p3[1]:.3f}, difference {v2p3[0] / v2p3[1] - v1p3[0] / v1p3[1]:+.3f}",
         None if not v2p3 else abs(v2p3[0] / v2p3[1] - v1p3[0] / v1p3[1]) <= 0.10 + 1e-9),
    ]
    L += ["## Table 8. Pre-registered predictions (airline_full/PLAN.md, section 3)", "",
          "| id | prediction | measured | verdict |", "|---|---|---|---|"]
    L += [f"| {p} | {d} | {m} | {verdict(v)} |" for p, d, m, v in preds]
    L.append("")
    (FULL / "summary_numbers.md").write_text("\n".join(L), encoding="utf-8")
    print("\n".join(L))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
