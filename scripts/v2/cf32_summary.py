"""Task-32 counterfactual (airline_full/PLAN.md, Q3): the ground-truth agent on task 32 of the v2 task set under the full
v2 protocol, 10 trials per arm. Arm A: the v2.1 text as published; arm B: the same text without "Any charge or refund
should go to your Visa credit card ending in 1777.". Reads results/v2/runs/v2_cf32_{A,B}_gt_haiku/results.json and
writes airline_full/cf32.md. No model call.
Usage (from ==Project):  python -I scripts/v2/cf32_summary.py
"""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]  # repo root (this file lives in scripts/v2/)
RUNS = ROOT / "results" / "v2" / "runs"
ARMS = {"A": "v2.1 text as published", "B": "the same text without the sentence on the Visa card"}


def main() -> int:
    sims, texts = {}, {}
    for arm in ARMS:
        data = json.loads((RUNS / f"v2_cf32_{arm}_gt_haiku" / "results.json").read_text(encoding="utf-8"))
        sims[arm] = sorted(data["simulations"], key=lambda s: int(s["trial"]))
        for s in sims[arm]:
            for i, a in enumerate((s.get("reward_info") or {}).get("nl_assertions") or []):
                texts.setdefault(i, a.get("nl_assertion", ""))
    passes = {arm: sum(1 for s in v if (s.get("reward_info") or {}).get("reward") == 1.0) for arm, v in sims.items()}
    diff = passes["B"] - passes["A"]
    L = ["# Task 32: does the payment sentence cause the ground-truth failures? (Q3)", "",
         "Ground-truth agent (`llm_agent_gt`, which sees the reference actions) on task 32 of the v2 task set under the full "
         "v2 protocol (scorer V2 with the 3-vote judge), Haiku 5.5 as agent, user simulator and judge, seed 300, 10 trials "
         "per arm (`scripts/v2/run_v2.py --part cf32_A` and `--part cf32_B`). Arm B removes the sentence \"Any charge or "
         "refund should go to your Visa credit card ending in 1777.\" from the user instructions; nothing else differs. "
         "Pre-registered rule (`airline_full/PLAN.md`, Q3): the sentence is taken to cause the failures if arm B passes at "
         "least 3 more of the 10 trials than arm A. Generated by `scripts/v2/cf32_summary.py`.", "",
         "| arm | text | passes |", "|---|---|---|"]
    L += [f"| {arm} | {ARMS[arm]} | {passes[arm]}/{len(sims[arm])} |" for arm in ARMS]
    L += ["", f"B - A = {diff}. " + ("At or above the threshold of 3: under the rule the sentence is taken to cause the failures."
                                    if diff >= 3 else "Below the threshold of 3: under the rule the sentence is not taken to "
                                    "cause the failures, and prediction P7 does not hold."), "",
          "Assertions of the task (judged under V2):", ""]
    L += [f"- assertion {i + 1}: {t}" for i, t in sorted(texts.items())]
    L += ["", "Per trial (DB = final database equals the reference end state; unmet = assertions the judge marked unmet):", "",
          "| arm | trial | reward | DB | unmet assertions | messages | termination |", "|---|---|---|---|---|---|---|"]
    fail_counts = {}
    for arm, v in sims.items():
        for s in v:
            ri = s.get("reward_info") or {}
            unmet = [i + 1 for i, a in enumerate(ri.get("nl_assertions") or []) if not a.get("met")]
            if ri.get("reward") != 1.0:
                for i in unmet:
                    fail_counts[(arm, i)] = fail_counts.get((arm, i), 0) + 1
            L.append(f"| {arm} | {s['trial']} | {ri.get('reward')} | {(ri.get('db_check') or {}).get('db_match')} | "
                     f"{', '.join(map(str, unmet)) or '-'} | {len(s.get('messages') or [])} | {s.get('termination_reason')} |")
    L += ["", "Failed trials per unmet assertion: " + "; ".join(
        f"arm {arm}: " + ", ".join(f"assertion {i}: {n}" for (a2, i), n in sorted(fail_counts.items()) if a2 == arm)
        for arm in ARMS) + ".", ""]
    (ROOT / "airline_full" / "cf32.md").write_text("\n".join(L), encoding="utf-8")
    print("\n".join(L[9:13]))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
